import Foundation

// Stands in for WireGen's contributor half: scans the library's own sources and
// writes a per-library manifest describing what it found, plus a generated
// Swift marker. Arguments: <manifest.json> <marker.swift> <source.swift…>.
//
// It derives the manifest from the sources rather than hardcoding it so that a
// change to the library produces a *different* manifest. That is what makes the
// harness's second phase a real test of the `inputFiles` edge: without the edge
// there is no reason for the consumer to re-run when only the manifest changed.
let arguments = CommandLine.arguments
let manifestPath = arguments[1]
let markerPath = arguments[2]
let sources = Array(arguments.dropFirst(3))

// The delay guards the *first* build: an unordered consumer command would run
// while this one is still sleeping. It makes a missing edge likely to fail on a
// clean build, where phase two makes it certain.
let delaySeconds = ProcessInfo.processInfo.environment["MANIFEST_HARNESS_DELAY"].flatMap(Double.init) ?? 2
Thread.sleep(forTimeInterval: delaySeconds)

var bindings: [String] = []
for source in sources {
    guard let contents = try? String(contentsOfFile: source, encoding: .utf8) else { continue }
    for line in contents.split(separator: "\n") {
        guard let range = line.range(of: "public struct ") else { continue }
        let name = line[range.upperBound...].prefix { $0.isLetter || $0.isNumber || $0 == "_" }
        if !name.isEmpty { bindings.append(String(name)) }
    }
}
bindings.sort()

let entries = bindings.map { #"{"type":"\#($0)","scope":"singleton"}"# }.joined(separator: ",")
let manifest = #"{"module":"ManifestHarnessLibrary","bindings":[\#(entries)]}"#
try manifest.write(toFile: manifestPath, atomically: true, encoding: .utf8)
try "// Generated by ManifestGen — the library's Wire-awareness marker.\n"
    .write(toFile: markerPath, atomically: true, encoding: .utf8)
FileHandle.standardError.write("ManifestGen: wrote \(bindings.count) binding(s)\n".data(using: .utf8)!)
